// T01 / NFR-1 peak scan load (docs/TESTING.md T01). Owner: Nam.
//
// Measures POST /api/local/scan on the kiosk: request -> kiosk response, which already carries the
// gate-command outcome. The background sync to central is NOT part of the number.
// Status: NOT_RUN until Khánh's scan replaces the 501 stub. setup() aborts the run on a 501, so this
// script cannot print a number for a route that does not exist.
//
// Each scan uses a different synthetic employee from tests/load/fixtures/load-employees.sql
// (LOAD-BD-0001 ..), so anti-replay never rejects a scan. The QR code is computed here exactly like
// user-qr's TotpCodeGenerator (RFC 6238, HMAC-SHA256 over the UTF-8 secret, 30 s, 6 digits);
// setup() checks that against Java vectors and against the live user-qr before any load starts.
//
// Scenarios (SCENARIO env):
//   steady   800 scans spread over 30 min for one factory (the NFR-1 workload)
//   burst    800 scans in 2 min (stress; report it separately from "steady")
//   quick    20 scans in 1 min, to check the setup before a long run (not evidence for NFR-1)
//   selftest TOTP vectors only, no network
//
// Env: KIOSK_URL (http://127.0.0.1:8085), GATEWAY_URL (http://127.0.0.1:8080), FACTORY_ID (BD),
//      LOAD_EMPLOYEES (1000, must match the fixture), GATES ("BD-G01:IN,BD-G02:OUT"),
//      WHITELIST_WAIT_S (120, how long setup() waits for the kiosk to learn the fixture).
// Commands: tests/load/README.md.

import http from 'k6/http';
import crypto from 'k6/crypto';
import exec from 'k6/execution';
import { check, sleep } from 'k6';
import { Rate, Trend } from 'k6/metrics';

const KIOSK = __ENV.KIOSK_URL || 'http://127.0.0.1:8085';
const GATEWAY = __ENV.GATEWAY_URL || 'http://127.0.0.1:8080';
const FACTORY = __ENV.FACTORY_ID || 'BD';
const EMPLOYEES = parseInt(__ENV.LOAD_EMPLOYEES || '1000', 10);
const WHITELIST_WAIT_S = parseInt(__ENV.WHITELIST_WAIT_S || '120', 10);
const GATES = (__ENV.GATES || 'BD-G01:IN,BD-G02:OUT').split(',').map((g) => {
  const [gateId, direction] = g.trim().split(':');
  return { gateId, direction };
});
const SCENARIO = __ENV.SCENARIO || 'steady';
const STEP_SECONDS = 30;
const NFR1_MS = 2000;
// The last fixture employee is reserved for the setup() probe; the load uses 1 .. EMPLOYEES-1.
const PROBE_NUMBER = EMPLOYEES;

const SCENARIOS = {
  steady: { executor: 'constant-arrival-rate', rate: 800, timeUnit: '30m', duration: '30m', preAllocatedVUs: 4, maxVUs: 20 },
  burst: { executor: 'constant-arrival-rate', rate: 400, timeUnit: '1m', duration: '2m', preAllocatedVUs: 20, maxVUs: 100 },
  quick: { executor: 'constant-arrival-rate', rate: 20, timeUnit: '1m', duration: '1m', preAllocatedVUs: 2, maxVUs: 5 },
  selftest: { executor: 'shared-iterations', vus: 1, iterations: 1 },
};
if (!SCENARIOS[SCENARIO]) {
  throw new Error(`Unknown SCENARIO=${SCENARIO}; use ${Object.keys(SCENARIOS).join(', ')}`);
}

const scanAllowed = new Rate('scan_allowed');
const scanWithinNfr1 = new Rate('scan_within_2s');
const gateCommandSent = new Rate('gate_command_sent');
const kioskProcessingMs = new Trend('kiosk_processing_ms', true);

export const options = {
  scenarios: { [SCENARIO]: SCENARIOS[SCENARIO] },
  setupTimeout: `${WHITELIST_WAIT_S + 60}s`,
  summaryTrendStats: ['avg', 'min', 'med', 'p(90)', 'p(95)', 'p(99)', 'max', 'count'],
  thresholds: SCENARIO === 'selftest' ? {} : {
    // NFR-1: scan -> kiosk response / gate command <= 2 s.
    'http_req_duration{endpoint:scan}': [`p(95)<=${NFR1_MS}`, `p(99)<=${NFR1_MS}`],
    'http_req_failed{endpoint:scan}': ['rate<0.01'],
    // Every scan is a fresh, valid code of a whitelisted employee: any REJECTED is a defect to explain.
    scan_allowed: ['rate==1'],
    // A load that k6 could not deliver on time is not the stated workload.
    dropped_iterations: ['count==0'],
  },
};

// ---- TOTP, same algorithm as user-qr TotpCodeGenerator --------------------------------------

function stepBytes(step) {
  const buf = new ArrayBuffer(8);
  const view = new DataView(buf);
  view.setUint32(0, Math.floor(step / 2 ** 32));
  view.setUint32(4, step % 2 ** 32);
  return buf;
}

export function totpAtStep(secret, step) {
  const hex = crypto.hmac('sha256', secret, stepBytes(step), 'hex');
  const b = [];
  for (let i = 0; i < hex.length; i += 2) b.push(parseInt(hex.substr(i, 2), 16));
  const offset = b[b.length - 1] & 0x0f;
  const binary = ((b[offset] & 0x7f) << 24) | (b[offset + 1] << 16) | (b[offset + 2] << 8) | b[offset + 3];
  return String(binary % 1000000).padStart(6, '0');
}

