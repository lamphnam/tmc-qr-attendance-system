function checkJavaVectors() {
  for (const [secret, step, expected] of JAVA_VECTORS) {
    const actual = totpAtStep(secret, step);
    if (actual !== expected) {
      exec.test.abort(`TOTP mismatch with Java for ${secret} step ${step}: got ${actual}, expected ${expected}`);
    }
  }
}

// ---- Fixture employees (must match tests/load/fixtures/load-employees.sql) ------------------

function employee(n) {
  const num = String(n).padStart(4, '0');
  return { empId: `LOAD-${FACTORY}-${num}`, secret: `TMC_LOAD_${FACTORY}_${num}_V1`, ver: 1 };
}

function scanBody(emp, gate) {
  const ts = Math.floor(Date.now() / 1000);
  return JSON.stringify({
    gateId: gate.gateId,
    direction: gate.direction,
    qrPayload: { empId: emp.empId, totp: totpAtStep(emp.secret, Math.floor(ts / STEP_SECONDS)), ts, ver: emp.ver },
  });
}

function postScan(emp, gate, tags) {
  return http.post(`${KIOSK}/api/local/scan`, scanBody(emp, gate), {
    headers: { 'Content-Type': 'application/json' },
    tags,
    timeout: '10s',
  });
}

function json(res) {
  try { return res.json(); } catch (e) { return null; }
}

// ---- setup: refuse to measure a broken or unprepared stack ---------------------------------

export function setup() {
  checkJavaVectors();
  if (SCENARIO === 'selftest') return {};

  // 1. The fixture is in central and user-qr computes the same code as this script.
  const first = employee(1);
  const qr = http.get(`${GATEWAY}/api/v1/qr/${first.empId}`, { tags: { endpoint: 'setup' } });
  if (qr.status === 404) {
    exec.test.abort(`${first.empId} is not in central: load tests/load/fixtures/load-employees.sql first`);
  }
  const qrBody = json(qr);
  if (qr.status !== 200 || !qrBody) {
    exec.test.abort(`GET /api/v1/qr/${first.empId} answered ${qr.status}; is the dev stack up on ${GATEWAY}?`);
  }
  const local = totpAtStep(first.secret, qrBody.timeStep);
  if (local !== qrBody.totpCode) {
    exec.test.abort(`TOTP parity with user-qr failed for ${first.empId} at step ${qrBody.timeStep}`);
  }

  // 2. The scan route exists and the kiosk already has the fixture in its whitelist.
  const probe = employee(PROBE_NUMBER);
  const deadline = Date.now() + WHITELIST_WAIT_S * 1000;
  for (;;) {
    const res = postScan(probe, GATES[0], { endpoint: 'setup' });
    if (res.status === 501) {
      exec.test.abort('POST /api/local/scan answers 501: the scan is not implemented, T01 stays NOT_RUN');
    }
    const body = json(res);
    if (res.status === 200 && body && body.result === 'ALLOWED') break;
    const reason = body && body.reason;
    // The fixture reaches the kiosk only through whitelist sync; wait for it instead of measuring rejections.
    if (reason === 'UNKNOWN_EMPLOYEE' && Date.now() < deadline) {
      sleep(5);
      continue;
    }
    exec.test.abort(`probe scan for ${probe.empId} was not ALLOWED (HTTP ${res.status}, result ${body && body.result}, `
      + `reason ${reason}). Check KIOSK_WHITELIST_SYNC_ENABLED, KIOSK_WHITELIST_KEY_BASE64 and the clock.`);
  }
  return {};
}

// ---- one scan per iteration, one employee per scan ------------------------------------------

export default function () {
  if (SCENARIO === 'selftest') return;

  const i = exec.scenario.iterationInTest;
  const n = i + 1;
  if (n >= PROBE_NUMBER) {
    exec.test.abort(`more scans than fixture employees (${EMPLOYEES - 1}); raise LOAD_EMPLOYEES and the fixture`);
  }
  const res = postScan(employee(n), GATES[i % GATES.length], { endpoint: 'scan' });
  const body = json(res);

  check(res, {
    'scan answers 200': (r) => r.status === 200,
    'scan result is ALLOWED': () => body !== null && body.result === 'ALLOWED',
  });
  scanAllowed.add(body !== null && body.result === 'ALLOWED');
  scanWithinNfr1.add(res.timings.duration <= NFR1_MS);
  // Mock turnstile: SENT means the command was accepted by the mock, not that a gate opened.
  gateCommandSent.add(body !== null && body.gateCommand === 'SENT');
  if (body !== null && typeof body.processingTimeMs === 'number') kioskProcessingMs.add(body.processingTimeMs);
}
